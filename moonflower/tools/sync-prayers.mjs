// Copies Moonflower's night prayers from A Simple Way to Pray's prayer library
// into index.html.
//
// A Simple Way to Pray (asimplewaytopray.com) is the one home for the prayers
// Hallowed Gains apps share: pastors review them there, and the site publishes
// them at LIBRARY_URL. This script takes the prayers Moonflower shows (WANTED)
// from that export and writes them into index.html, between the PRAYERS:BEGIN
// and PRAYERS:END lines, which are committed. The game never fetches prayers
// while it runs: it works with no internet (sw.js), an outage there can't
// break it, and no request ever says who was praying, or when.
//
// It's the same pattern as Early Bloom's scripts/sync_prayers.py. Run it when
// the library changes, then look over the diff and push as usual:
//
//   node tools/sync-prayers.mjs                    fetch the live library
//   node tools/sync-prayers.mjs --from FILE.json   use a saved export
//   node tools/sync-prayers.mjs --check            exit 1 if index.html is out of date
//
// Node 18 or later, with no packages. The export's contract (schema 1) is in
// A Simple Way to Pray's docs/prayer-library.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LIBRARY_URL = 'https://asimplewaytopray.com/api/prayers/v1/library.json';
const SCHEMA = 1;
const PAGE = join(dirname(fileURLToPath(import.meta.url)), '..', 'index.html');

// The prayers the night prayer page shows, in this order. They're looked up by
// id, and an id in the library never changes, so a renamed title still syncs.
const WANTED = [
  'night-feed',            // "In the night feeds", written for Moonflower
  'watch-thou-dear-lord',  // "For those who wake", the Book of Common Prayer
  'luther-evening',        // Luther's Evening Prayer, from the Small Catechism
];
// The fields the page uses. Anything else in the export stays out.
const FIELDS = ['id', 'title', 'paragraphs', 'credit', 'url'];

const BEGIN = '// PRAYERS:BEGIN';
const END = '// PRAYERS:END';

/** Throws unless `library` is a schema-1 export holding every WANTED prayer. */
function validate(library) {
  if (!library || library.schema !== SCHEMA) {
    throw new Error(`expected schema ${SCHEMA}: a new schema means a new URL and a change to this script`);
  }
  if (typeof library.version !== 'string' || !library.version) throw new Error('the export has no version');
  if (!Array.isArray(library.prayers)) throw new Error('the export has no prayers');
  for (const id of WANTED) {
    const p = library.prayers.find(x => x.id === id);
    if (!p) throw new Error(`the library has no prayer "${id}"`);
    for (const f of ['title', 'credit']) if (typeof p[f] !== 'string' || !p[f]) throw new Error(`prayer "${id}" has no ${f}`);
    if (!Array.isArray(p.paragraphs) || !p.paragraphs.length || !p.paragraphs.every(s => typeof s === 'string' && s)) {
      throw new Error(`prayer "${id}" has an empty paragraph`);
    }
  }
  return library;
}

/** The lines that go between the markers. */
function render(library) {
  const prayers = WANTED.map(id => {
    const p = library.prayers.find(x => x.id === id);
    return Object.fromEntries(FIELDS.map(f => [f, p[f] ?? null]));
  });
  // JSON is valid JavaScript. Escaping "<" keeps a stray "</script>" in a
  // prayer from ever closing the page's script early.
  const json = JSON.stringify(prayers, null, 2).replace(/</g, '\\u003c');
  return [
    `${BEGIN}: generated by tools/sync-prayers.mjs from A Simple Way to Pray's prayer`,
    `// library (${LIBRARY_URL}, version ${library.version}). Edit the prayers there, not here.`,
    `const PRAYERS = ${json};`,
    END,
  ].join('\n');
}

async function fetchLibrary() {
  const res = await fetch(LIBRARY_URL, { headers: { 'User-Agent': 'Moonflower-sync-prayers/1' } });
  if (!res.ok) throw new Error(`${LIBRARY_URL}: HTTP ${res.status}`);
  return res.json();
}

async function main(argv) {
  const at = argv.indexOf('--from');
  const library = validate(at >= 0 ? JSON.parse(readFileSync(argv[at + 1], 'utf8')) : await fetchLibrary());
  const page = readFileSync(PAGE, 'utf8');
  const i = page.indexOf(BEGIN), j = page.indexOf(END, i);
  if (i < 0 || j < 0) throw new Error(`index.html has no ${BEGIN} … ${END} block`);
  const next = page.slice(0, i) + render(library) + page.slice(j + END.length);

  if (argv.includes('--check')) {
    console.log(next === page ? `Up to date (library version ${library.version}).`
      : `Out of date: run node tools/sync-prayers.mjs (library version ${library.version}).`);
    return next === page ? 0 : 1;
  }
  if (next === page) { console.log(`Already up to date (library version ${library.version}).`); return 0; }
  writeFileSync(PAGE, next);
  console.log(`Wrote ${WANTED.length} prayers into index.html (library version ${library.version}).`);
  return 0;
}

main(process.argv.slice(2)).then(code => process.exit(code), err => { console.error(`sync-prayers: ${err.message}`); process.exit(2); });
